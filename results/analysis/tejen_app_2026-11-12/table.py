"""Per-trial table of Te-Jen's application demos (card docs/experiments/2026-11-11_tejen_app_demos.md).
python3 results/analysis/tejen_app_2026-11-12/table.py  -> table.md beside it (reads the run dirs listed in CASES)."""
import csv, glob, math, os, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import app_demo_figure as F  # noqa: E402

CASES = {
    'hover, 1 m cables (bands 0.05)': ['R4254', 'R4257', 'R4260', 'R4275', 'R4276'],
    'hover, 0.55 m cables': ['R4291', 'R4294', 'R4297', 'R4300', 'R4303'],
    'circle 0.5 m at 0.125 m/s, 0.55 m cables': ['R4288', 'R4292', 'R4295', 'R4298', 'R4301'],
    'figure-eight 1.0 m at 0.08 m/s, 0.55 m cables (looser limits, give-up 120 s)': ['R4306', 'R4307', 'R4308', 'R4309', 'R4310'],
    'figure-eight 1.0 m at 0.125 m/s, 0.55 m cables (not used: no attach)': ['R4290', 'R4293', 'R4296', 'R4299', 'R4305'],
    'circle 0.3 m and figure-eight 1.0 m, 1 m cables (not used: no attach)': ['R4255', 'R4258', 'R4269', 'R4271', 'R4272', 'R4273', 'R4274', 'R4285', 'R4286', 'R4287', 'R4289'],
}


def run_dir(rid):
    d = glob.glob(os.path.join(ROOT, 'results', '2026-11-1*', f'{rid}_sim_gz_*'))
    return d[0] if d else None


def row(rid):
    d = run_dir(rid)
    if d is None or not os.path.exists(os.path.join(d, 'logs', 'run.csv')):
        return None
    data, ev = F.load(d)
    s = F.summary(d, data, ev)
    abort = next((t for t, e in ev if e == 'FLEET_ABORT'), None)
    land = s.get('LAND (s)')
    att = s.get('attach confirmed (s)')
    return {
        'run': rid, 'attach': 'yes' if att is not None else 'no',
        'takeoff to attach (s)': s.get('takeoff to attach (s)', '-'),
        'pickup / attach descents': f"{s['pickup descents']} / {s['attach descents']}",
        'object from ring centre (cm)': s.get('ball from ring centre 5 s after drop (cm)', '-'),
        'ring speed at drop / attach (m/s)': f"{s.get('ring speed at drop (m/s)', '-')} / {s.get('ring speed at attach confirmed (m/s)', '-')}",
        'ring path error rms / max (cm)': '%s / %s' % tuple(s.get('ring path error rms / max (cm)', ('-', '-'))),
        'ring tilt peak (deg)': s.get('ring tilt peak in flight (deg)', '-'),
        'landing': '-' if land is None else ('abort %.1f s after LAND' % (abort - land) if abort is not None and abort > land else 'landed'),
    }


def main():
    out = ['# Te-Jen\'s application demos: every trial (simulation)', '',
           'Generated by table.py from the run directories. "Attach" = our co-motion check confirmed the weld. Landing aborts',
           'after the attach are the twin\'s landing effect (TB14), after the task.', '']
    for case, rids in CASES.items():
        rows = [r for r in (row(x) for x in rids) if r]
        if not rows:
            continue
        n = sum(r['attach'] == 'yes' for r in rows)
        out += [f'## {case}: attached in {n} of {len(rows)}', '']
        keys = list(rows[0])
        out += ['| ' + ' | '.join(keys) + ' |', '|' + '---|' * len(keys)]
        out += ['| ' + ' | '.join(str(r[k]) for k in keys) + ' |' for r in rows]
        out.append('')
    open(os.path.join(HERE, 'table.md'), 'w').write('\n'.join(out) + '\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
