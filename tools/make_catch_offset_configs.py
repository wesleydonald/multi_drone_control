REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, 'configs', 'experiments')
CARD = 'docs/experiments/2026-10-23_catch_offset.md'
GRID_CM = (2, 4, 6, 8, 12, 16)
# plate 10's centre from plate 9 (the 30-deg chord at r 0.225, 11.6 cm): the one off-slot weld a real magnet makes, on
# the wrong plate (critic M3); along the rim only
WRONG_PLATE_CM = round(200.0 * 0.225 * math.sin(math.pi / 12.0), 3)
NEIGHBOURS = (('meas', 'ta', 8), ('meas', 'ro', 8), ('slot', 'ro', 8))
EXTENSION = (('meas', 't', 20), ('slot', 't', 20), ('meas', 'ri', 20), ('slot', 'ri', 20))
ARM = {'meas': 'measured', 'slot': 'slot'}
ARM_TEXT = {'meas': 'the fold-in at the measured catch point (as flown, the rig\'s)',
            'slot': 'the fold-in at the slot (the slot assumed)'}
DIR_TEXT = {'t': 'along the rim, clockwise (toward the plate-11 carrier)', 'ta': 'along the rim, anticlockwise',
            'ri': 'radially in', 'ro': 'radially out'}
# R2420 (V4 = E1, G26): the weld 32 s after MAGNET ON, i.e. ~37 s after the lift's top here; + 35 s, up to 5 s
TRAJ_HOLD_S = 75.0
PARAMS_FILE = '/home/wesley/multi_drone_control/configs/rig/drop_and_land_hold5.yaml'


def offsets(direction, cm):
    """(catch_offset_t, catch_offset_r) in m."""
    d = round(cm / 100.0, 5)
    return {'d': (0.0, 0.0), 't': (d, 0.0), 'ta': (-d, 0.0), 'ri': (0.0, -d), 'ro': (0.0, d)}[direction]


def name(arm, direction, cm):
    """u_meas_t04; a cm with a decimal keeps it without the point (t116 = 11.6 cm)."""
    if direction == 'd':
        return f'u_{arm}_d00'
    return f'u_{arm}_{direction}' + (f'{cm:02d}' if cm == int(cm) else f'{round(10 * cm):03d}')


def variants():
    """[(arm, direction, cm, kind)]: the grid (both arms, d = 0 and GRID_CM along the rim and radially in), the
    neighbours (flown once) and the pre-registered 20 cm extension (only where nothing failed by 16 cm)."""
    out = []
    for arm in ('meas', 'slot'):
        out.append((arm, 'd', 0, 'grid'))
        out += [(arm, direction, cm, 'grid') for direction in ('t', 'ri') for cm in GRID_CM]
        out.append((arm, 't', WRONG_PLATE_CM, 'grid'))
    out += [(arm, direction, cm, 'neighbour') for arm, direction, cm in NEIGHBOURS]
    out += [(arm, direction, cm, 'extension') for arm, direction, cm in EXTENSION]
    return out


def description(arm, direction, cm, kind):
    where = ('on the slot (plate 9, (0, 0.225))' if direction == 'd'
             else f'on plate 10\'s centre, {cm:.1f} cm {DIR_TEXT[direction]} off the slot (a wrong-plate catch)'
             if cm == WRONG_PLATE_CM else f'{cm} cm {DIR_TEXT[direction]} off the slot')
    role = {'grid': 'the claim grid (2 repeats)',
            'neighbour': 'a neighbour of the grid, flown once (exploratory, 24 Sep rule)',
            'extension': 'the pre-registered extension, flown only for a direction where neither arm failed by 16 cm'
            }[kind]
    return (f'Sim U ({CARD}; Wesley 22 Oct, push answer 17): the magnet catches {where}; {ARM_TEXT[arm]}. '
            f'{role.capitalize()}. M1 layout at 1 m: carriers on plates 3/11/7, the free 1 m newcomer on our own '
            f'approach to the moved weld point (as-built trigger: radius 0.025 at weld_point_z 0.04, gate 0.05 m/s), '
            f'magnet ON in the hover hold, fold-in on a still ring, 4-quad hover, one figure-8 (size 1.0, 0.2 m/s), '
            f'LAND. Scored by '
            f'tools/catch_offset.py against the card\'s bars (PROPOSED until frozen). Generated by '
            f'tools/make_catch_offset_configs.py: do not edit by hand.')


