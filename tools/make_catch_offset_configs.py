"""tools/make_catch_offset_configs.py -- the run configs of thesis sim result U (card
docs/experiments/2026-10-23_catch_offset.md), written from one template so that a pair differs only in its one variable.

    python3 tools/make_catch_offset_configs.py           # (re)write configs/experiments/u_*.yaml
    python3 tools/make_catch_offset_configs.py --check   # exit 1 if any is stale, missing or not generated here

Every config: the M1 layout at 1 m (carriers on plates 3/11/7, the free QUAD4-like newcomer to plate 9 on our own
approach), magnet ON in the hover hold, the weld and fold-in on a still ring, the 4-quad hover, one figure-8 (size 1.0,
0.2 m/s), LAND. The weld trigger is the as-built twin's (radius 0.025 at weld_point_z 0.04, speed gate 0.05 m/s) around
the moved weld point. Names: u_<arm>_<offset>, arm meas (the measured catch point) or slot (the slot assumed); offset
d00, t<cm> along the rim clockwise, ta<cm> anticlockwise, ri<cm> radially in, ro<cm> radially out; t116 is plate 10's
centre (11.6 cm, the wrong-plate catch).
"""
import argparse
