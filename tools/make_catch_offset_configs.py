def render(cfg):
    return yaml.safe_dump(cfg, sort_keys=False, default_flow_style=False, width=120)


def generated():
    return {f"{c['name']}.yaml": render(c) for c in (config(*v) for v in variants())}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--check', action='store_true', help='exit 1 if any config is stale, missing or not generated')
    o = ap.parse_args(argv)
    want = generated()
    if o.check:
        bad = [f for f, text in want.items()
               if not os.path.exists(os.path.join(OUT, f)) or open(os.path.join(OUT, f)).read() != text]
        bad += [os.path.basename(p) + ' (not generated here)' for p in sorted(glob.glob(os.path.join(OUT, 'u_*.yaml')))
                if os.path.basename(p) not in want]
        if bad:
            print('stale: ' + ', '.join(bad) + ' (rerun tools/make_catch_offset_configs.py)')
            return 1
        print(f'ok    {len(want)} U configs up to date')
        return 0
    for f, text in want.items():
        with open(os.path.join(OUT, f), 'w') as fh:
            fh.write(text)
    print(f'wrote {len(want)} configs: ' + ', '.join(sorted(want)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
