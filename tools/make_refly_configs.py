#!/usr/bin/env python3
"""tools/make_refly_configs.py -- thesis R: every 0.55 m twin table re-flown at 1 m (card
docs/experiments/2026-10-23_refly_1m.md). Writes configs/experiments/r1m_<source>.yaml from each source config the
tables cite (tools/thesis_runsets.py), changed only in what the cable length needs.

    python3 tools/make_refly_configs.py                  # (re)write the r1m_*.yaml
    python3 tools/make_refly_configs.py --check          # exit 1 if any is stale, missing or not generated here
    python3 tools/make_refly_configs.py --list           # what is generated, and what waits for a 1 m world
    python3 tools/make_refly_configs.py --order lab      # the batch, one path per line (smoke: the first look)

The transform:
- the world becomes its 1 m sibling (<world>_L100.sdf); a source whose sibling does not exist is skipped (a world SDF
  is Wesley's word), so is any cable length but 0.55 or 0.60 (the typed +5 cm rod error keeps its absolute size);
- cable_len + 0.45; a typed io tether_len becomes the world's 1.0; a typed attach_cable_len is dropped (1 m configs
  leave it untyped, push answer 2);
- a path with no hover hold (in its args or its params_file) gets traj_hold_s HOLD_S and every event after WAIT_LIFT
  that much later; hovers and the paths that already hold are not shifted;
- the figure-8 keeps the size it flew (fig8_size as typed) unless FIG8_SIZE is set, which also moves LAND and every
  later event by the longer lap (LoadTrajectory);
- duration_s + the shift + DURATION_EXTRA_S (the traj3_L100 rule: the 1 m creep and landing);
- lab_env: the carriers' mocap velocity filter FILTER (one value for every R config; push answer 7), the ring's ema,
  and every carrier listed (G20);
- record: the B baseline camera, 30 fps state log, no render during the run;
- name r1m_<source> and a description naming the card, the source and its 0.55 m runs.
"""
import argparse
import copy
import glob
import math
import os
import sys

import yaml

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, 'tools'))
import thesis_runsets as RS  # noqa: E402

OUT = os.path.join(REPO, 'configs', 'experiments')
FILTER = 'ema'
HOLD_S = 5.0
FIG8_SIZE = None
DURATION_EXTRA_S = 15.0
CABLE_STEP = 0.45
CABLES = (0.55, 0.60)
CAMERA = {'baseline': {'pos': [2.0, -4.6, 2.9], 'look_at': [0.35, 0.0, 1.1], 'hfov_deg': 60.0, 'size': [1280, 720]}}
RECORD = {'period_s': 0.0333, 'fps': 30, 'render': False, 'cameras': CAMERA}
HEADER = ('# GENERATED by tools/make_refly_configs.py from configs/experiments/{src}.yaml: '
          'edit the generator, not this file\n')


class Skip(Exception):
    """A source that cannot be re-flown at 1 m without something only Wesley can give (a world)."""


def load(name):
    with open(os.path.join(OUT, name + '.yaml')) as fh:
        src = yaml.safe_load(fh)
    src.setdefault('name', name)
    return src


def held(args):
    """The hover hold a config already flies (its args, else its params_file), or None."""
    if args.get('traj_hold_s') not in (None, ''):
        return float(args['traj_hold_s'])
    sys.path.insert(0, os.path.join(REPO, 'tools'))
    from experiment.config import params_file_knobs
    v = params_file_knobs(args.get('params_file')).get('traj_hold_s')
    return None if v in (None, '') else float(v)


def fig8_lap_s(size, speed):
    sys.path.insert(0, os.path.join(REPO, 'src', 'mpc_planner'))
    from mpc_planner.load_trajectory import LoadTrajectory
    return LoadTrajectory('fig_8', speed, 1.0, size)._fig8_theta(0.0)[3]


def _land_t(events):
    lands = [float(e['t']) for e in events if e['do'] == 'LAND']
    return min(lands) if lands else math.inf


def transform(src, old_runs=()):
    """(r1m config, notes) for one 0.55 m source; raises Skip where it cannot be made without a new world."""
    c = copy.deepcopy(src)
    a = c['launch']['args']
    world = RS.world_1m(c['world'])
    if world is None:
        raise Skip(f"{src['name']}: no 1 m world {c['world'][:-len('.sdf')]}_L100.sdf")
    c['world'] = world
    cable = float(a['cable_len'])
    if not any(math.isclose(cable, v) for v in CABLES):
        raise Skip(f"{src['name']}: cable_len {cable} is not one of {CABLES}")
    a['cable_len'] = round(cable + CABLE_STEP, 3)
    a.pop('attach_cable_len', None)
    io = c.get('io_launch', {}).get('args', {})
    if 'tether_len' in io:
        io['tether_len'] = 1.0
    kind = str(a.get('load_traj', 'hover'))
    notes, shift, lap_extra = [], 0.0, 0.0
    if kind != 'hover':
        h = held(a)
        if h is None:
            a['traj_hold_s'] = HOLD_S
            shift = HOLD_S
            notes.append(f'a {HOLD_S:g} s hover hold before the path (events after WAIT_LIFT +{HOLD_S:g} s)')
        else:
            notes.append(f'its {h:g} s hold kept')
    if kind == 'fig_8':
        size = float(a['fig8_size'])
        if FIG8_SIZE is not None and not math.isclose(size, FIG8_SIZE):
            lap_extra = float(math.ceil(fig8_lap_s(FIG8_SIZE, float(a['traj_speed']))
                                        - fig8_lap_s(size, float(a['traj_speed']))))
            a['fig8_size'] = FIG8_SIZE
            notes.append(f'figure-8 size {FIG8_SIZE:g} (flew {size:g}; LAND +{lap_extra:g} s)')
        else:
            notes.append(f'figure-8 size {size:g} as flown')
    land = _land_t(src['events'])
    after = False
    for e in c['events']:
        if after:
            e['t'] = round(float(e['t']) + shift + (lap_extra if float(e['t']) >= land else 0.0), 3)
        after = after or e['do'] == 'WAIT_LIFT'
    c['timing']['duration_s'] = round(float(c['timing']['duration_s']) + shift + lap_extra + DURATION_EXTRA_S, 3)
    n = int(c['fleet']['num_drones'])
    c['lab_env'] = {'SIM_MOCAP_VEL_FILTER': FILTER, 'SIM_MOCAP_VEL_RING': 'ema',
                    'MDC_MOCAP_VEL_DRONES': ','.join(str(i) for i in range(n))}
    c['record'] = copy.deepcopy(RECORD)
    c['name'] = RS.PREFIX + src['name']
    first = ' '.join(str(src.get('description') or '').split()).split('. ')[0]
    if len(first) > 300:
        first = first[:300].rsplit(' ', 1)[0] + ' ...'
    ran = f"Scored against the 0.55 m runs {', '.join(old_runs)}" if old_runs else 'No 0.55 m run of its own'
    c['description'] = (f"Thesis R, the 1 m re-fly ({RS.CARD}): {src['name']} with 1 m cables (world {world}, "
                        f"cable_len {a['cable_len']}); {'; '.join(notes + [f'the twin mocap filter {FILTER} typed'])}. "
                        f"{ran}. Source: {first}. Generated by tools/make_refly_configs.py: do not edit by hand.")
    return c, notes


def old_runs_of(config):
    for t in RS.TABLES.values():
        for cell in t['cells']:
            if cell['config'] == config:
                return cell['old']
    return []


def build():
    """({file: text}, {source: skip reason})."""
    want, skipped = {}, {}
    for name in RS.sources():
        try:
            c, _ = transform(load(name), old_runs_of(name))
        except Skip as e:
            skipped[name] = str(e)
            continue
        want[c['name'] + '.yaml'] = HEADER.format(src=name) + yaml.safe_dump(
            c, sort_keys=False, default_flow_style=False, width=120)
    return want, skipped


def order(which='lab'):
    """Config paths in batch order, each listed as often as it flies. lab: the 1 m W4 ledger cell first (its band is
    needed before Thu 29), then the detach block (r1 wave, r2, r3), the carry block (0.125 m/s first; r1 wave, then
    r2), the appendix's Chapter-4 subset (r1, r2), then the appendix-only cells (r1, r2). smoke: one of each family."""
    want, _ = build()
    have = {f[:-len('.yaml')][len(RS.PREFIX):] for f in want}
    reps = RS.sources()
    if which == 'smoke':
        seq = ['ta_a1_r1', 'ta_a6_r1', 'traj3_fig8_v300', 'traj3_spin_v300', 'w4_gi_g2_release_orbit',
               'app_land_straight', 'dl_d1_second_loss', 'app_mapneg_model']
        return [_path(s) for s in seq if s in have]
    detach = (['ta_a1', 'ta_a2', 'ta_a5', 'ta_a6'],
              ['ta_a7_circle60', 'ta_a8_circle60', 'w4_gi_g2_release_orbit', 'dl_d1_second_loss', 'dl_d4_gap240'])
    tb = [f'tb_{g}' for g in ('g135', 'g150', 'g150p', 'g165', 'g180')]
    carry = [f'traj3_{s}_v{v}' for v in RS.SPEEDS for s in RS.SHAPES]
    ch4 = ['app_x0_hold_eps0', 'app_x0_hold_eps025', 'app_x0_orbit_eps0', 'app_x0_orbit_eps025', 'app_pushz_none',
           'app_pushz_ref', 'app_pushz_model', 'app_push04_none', 'app_push04_model', 'app_mapneg_ref',
           'app_mapneg_model', 'app_rob_none_int']
    seq = ['w4_da_release_hover'] * reps['w4_da_release_hover']
    for r in (1, 2, 3):
        seq += [f'{a}_r{r}' for a in detach[0]] + [f'{g}_r{r}' for g in tb if r <= 2]
        seq += [s for s in detach[1] if reps[s] >= r] + (['tb_g180drop_r1'] if r == 1 else [])
    for group in (carry, ch4, [s for s in reps if s.startswith('app_') and s not in ch4]):
        for r in (1, 2, 3):
            seq += [s for s in group if reps.get(s, 0) >= r]
    seen = set(seq)
    assert seen == set(reps), sorted(set(reps) ^ seen)
    return [_path(s) for s in seq if s in have]


def _path(source):
    return f'configs/experiments/{RS.PREFIX}{source}.yaml'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument('--check', action='store_true', help='exit 1 if any config is stale, missing or not generated')
    g.add_argument('--list', action='store_true', help='generated configs and the sources waiting for a world')
    g.add_argument('--order', choices=['lab', 'smoke'], help='print the batch, one config path per line')
    o = ap.parse_args(argv)
    want, skipped = build()
    if o.order:
        print('\n'.join(order(o.order)))
        return 0
    if o.list:
        reps = RS.sources()
        for f in sorted(want):
            print(f"{f:44s} x{reps[f[len(RS.PREFIX):-len('.yaml')]]}")
        for s, why in sorted(skipped.items()):
            print(f'skipped {why}')
        return 0
    if o.check:
        bad = [f for f, text in want.items()
               if not os.path.exists(os.path.join(OUT, f)) or open(os.path.join(OUT, f)).read() != text]
        bad += [os.path.basename(p) + ' (not generated here)'
                for p in sorted(glob.glob(os.path.join(OUT, RS.PREFIX + '*.yaml'))) if os.path.basename(p) not in want]
        if bad:
            print('stale: ' + ', '.join(bad) + ' (rerun tools/make_refly_configs.py)')
            return 1
        print(f'ok    {len(want)} R configs up to date ({len(skipped)} sources wait for a 1 m world)')
        return 0
    for f, text in want.items():
        with open(os.path.join(OUT, f), 'w') as fh:
            fh.write(text)
    print(f'wrote {len(want)} configs; {len(skipped)} skipped: ' + '; '.join(sorted(skipped.values())))
    return 0


if __name__ == '__main__':
    sys.exit(main())
