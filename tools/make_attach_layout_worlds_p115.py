#!/usr/bin/env python3
"""tools/make_attach_layout_worlds_p115.py -- the square's attach worlds on the payload of 28 Oct (RIG-1028-payload).

make_attach_layout_worlds_L100.py's square (carriers on rig plates 0/3/6, QUAD4 joins plate 9) with
make_carry_worlds_p115.py's ring: 1.15 kg, magnets at r 0.204, plate faces 0.025 above the centre of mass, 26 mm thick
(the centre of mass rests at 0.013), outer r 0.255, the inertia rewritten to 0.0246 / 0.0246 / 0.049.

    sq_rigid_ground_rig_attach_pickup_L100_p115.sdf          free start (floor_join, pickup_delivery)
    sq_rigid_ground_rig_attach_welded_pickup_L100_p115.sdf   QUAD4 welded on plate 9 from spawn
    models/x3_rig_drone3_magnet_welded_pickup_L100_p115.sdf  the welded newcomer, its arm down to the new plate

--spawn far (card 2026-10-28_attach_ambitious, the avoidance demo): QUAD4's mat behind the T, between the plate-3
and plate-6 carriers, its arm laid out away from the ring, so floor_join's C++ transit has to fly round the carriers:

    sq_far_rigid_ground_rig_attach_pickup_L100_p115.sdf      the free world with QUAD4 on the far mat
    models/x3_rig_drone3_magnet_far_pickup_L100.sdf          the free pickup newcomer, its arm's pose turned

The free newcomer and the ball are the 1 m family's (checked identical). The open ring is make_attach_worlds' annulus
on the generator's 60 mm rim (r 0.195-0.255) with the net across it: the payload's netted hole is r 0.135, so the
twin's net is wider than the real one.

    python3 tools/make_attach_layout_worlds_p115.py [--check] [--spawn near|far]   (default both)
"""
import argparse
import contextlib
import math
import os
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_attach_worlds as maw  # noqa: E402
import make_attach_worlds_L100 as L100  # noqa: E402
import make_attach_layout_worlds_L100 as layout  # noqa: E402
import make_carry_worlds_p115 as p115  # noqa: E402

SUFFIX = '_p115'
AZIMUTHS, PLATES = layout.LAYOUTS['sq']
ATTACH_RADIUS = 0.204
ATTACH_Z = 0.025
RING_THICKNESS = p115.RING_THICKNESS
RIM = 0.060                       # generate_rigid_world.RING_SEG_RADIAL: the ring visuals' radial width
# the carry worlds' ring options, without their tether pose rate (the attach family has none)
RING_ARGS = ['--payload-mass', str(p115.LOAD_MASS), '--attach-radius', str(ATTACH_RADIUS), '--attach-z', str(ATTACH_Z),
             '--ring-outer-r', str(maw.RING_OUTER_R), '--ring-thickness', str(RING_THICKNESS)]
HEADER = '<!-- GENERATED by tools/make_attach_worlds.py: do not edit.'
NEW_HEADER = ('<!-- GENERATED by tools/make_attach_layout_worlds_p115.py (make_attach_worlds.py, the square, the 1.15 kg '
              'payload of 28 Oct): do not edit.')
RIM_NOTE = f'rim centred on the plates (r {ATTACH_RADIUS})'
NEW_RIM_NOTE = f'rim of the ring visuals (plates at r {ATTACH_RADIUS}; the payload\'s netted hole is r 0.135)'
SPAWNS = ('near', 'far')          # near: make_attach_worlds' free start, (0, 1.4) with the arm out along +y
# the far mat: >= FAR_CLEAR from each carrier's floor spot, and the laid-out arm >= FAR_CLEAR from each carrier's
# cable on the floor. The body spawns at yaw 0 (his reference yaw: a turned body would sweep the arm over the floor
# at takeoff), so the arm's own pose turns about the pivot.
FAR_XY = (-1.0, -1.0)
FAR_CLEAR = 0.9


def carrier_world():
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, 'w.sdf')
        subprocess.run([sys.executable, maw.GEN, '--n', '3', '--azimuths', AZIMUTHS, *maw.RIG_ARGS, '--out', out],
                       check=True, cwd=maw.ASSETS, stdout=subprocess.DEVNULL)
        with open(out) as f:
            text = f.read()
    text, k = p115.INERTIA.subn(rf'\g<1><ixx>{p115.LOAD_IXX:.4e}</ixx>\g<2><iyy>{p115.LOAD_IXX:.4e}</iyy>\g<3>'
                                rf'<izz>{p115.LOAD_IZZ:.4e}</izz>', text, count=1)
    if k != 1:
        raise SystemExit('no payload inertia to rewrite')
    return text


def ball_clearance(base, start='free'):
    """make_attach_worlds.ball_clearance for these carriers (make_attach_layout_worlds_L100's)."""
    carriers = re.findall(r'<name>x3_drone[0-2]</name>\s*<pose>(\S+) (\S+)', base)
    if len(carriers) != 3:
        raise SystemExit('carrier poses not found in the base world')
    near_carrier = min(math.dist(maw.BALL_XY, (float(x), float(y))) for x, y in carriers)
    (x, y, _), roll = maw.spawn(start)
    tip_y = y + maw.CABLE_LEN * math.sin(roll)
    lo, hi = min(y, tip_y), max(y, tip_y)
    return near_carrier, math.dist(maw.BALL_XY, (x, min(max(maw.BALL_XY[1], lo), hi)))


@contextlib.contextmanager
def p115_ring():
    """make_attach_worlds on the 1 m family with the 28 Oct payload and the square's carriers, restored afterwards."""
    names = ('RIG_ARGS', 'ATTACH_RADIUS', 'WELD_Y', 'PLATE_Z', 'RING_THICKNESS', 'RING_INNER_R', 'RING_COLLISION',
             'RING_COLLISION_MASKED', 'CARRIER_AZIMUTHS', 'carrier_world', 'ball_clearance', 'MODELS', 'PICKUP_MODELS')
    with L100.one_metre():
        keep = {k: getattr(maw, k) for k in names}
        maw.RIG_ARGS = list(keep['RIG_ARGS']) + RING_ARGS       # later options win
        maw.ATTACH_RADIUS = maw.WELD_Y = ATTACH_RADIUS
        maw.RING_THICKNESS = RING_THICKNESS
        maw.PLATE_Z = RING_THICKNESS / 2.0 + ATTACH_Z          # the plate face, the ring on the floor
        maw.RING_INNER_R = maw.RING_OUTER_R - RIM
        maw.RING_COLLISION = keep['RING_COLLISION'].replace(f'<length>{keep["RING_THICKNESS"]:.3f}</length>',
                                                            f'<length>{RING_THICKNESS:.3f}</length>')
        maw.RING_COLLISION_MASKED = keep['RING_COLLISION_MASKED'].replace(
            f'<length>{keep["RING_THICKNESS"]:.3f}</length>', f'<length>{RING_THICKNESS:.3f}</length>')
        maw.CARRIER_AZIMUTHS, maw.carrier_world, maw.ball_clearance = AZIMUTHS, carrier_world, ball_clearance
        # the welded arm reaches the new plate: its own model; the free newcomer is the 1 m family's
        maw.MODELS = {**keep['MODELS'], 'welded': keep['MODELS']['welded'].replace('.sdf', f'{SUFFIX}.sdf')}
        maw.PICKUP_MODELS = {**keep['PICKUP_MODELS'],
                             'welded': keep['PICKUP_MODELS']['welded'].replace('.sdf', f'{SUFFIX}.sdf')}
        try:
            yield
        finally:
            for k, v in keep.items():
                setattr(maw, k, v)


def _once(text, old, new, what):
    if text.count(old) != 1:
        raise SystemExit(f'{what}: not found exactly once')
    return text.replace(old, new)


def _to_segment(p, a, b):
    dx, dy = b[0] - a[0], b[1] - a[1]
    t = max(0.0, min(1.0, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy)))
    return math.dist(p, (a[0] + t * dx, a[1] + t * dy))


def _segments(a, b, c, d):
    """The distance between floor segments ab and cd."""
    def side(p, q, r):
        return (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0])
    if side(a, b, c) * side(a, b, d) < 0 and side(c, d, a) * side(c, d, b) < 0:
        return 0.0
    return min(_to_segment(a, c, d), _to_segment(b, c, d), _to_segment(c, a, b), _to_segment(d, a, b))


def far_spawn(name, world, free_model, model, spawn):
    """{name: text} of the free world (name, text) and its newcomer (free_model, text) with QUAD4 on the far mat
    (FAR_XY), the arm laid out away from the ring. spawn: make_attach_worlds' ((x, y, z), roll, reach, ball xy) of
    the free start on the 1 m family."""
    (x, y, z), roll, reach, ball_xy = spawn
    ux, uy = (v / math.hypot(*FAR_XY) for v in FAR_XY)
    yaw = math.atan2(-ux, uy)                    # turns the arm's body +y onto (ux, uy)
    tip = (FAR_XY[0] + reach * ux, FAR_XY[1] + reach * uy)
    carriers = [(float(a), float(b)) for a, b in re.findall(r'<name>x3_drone[0-2]</name>\s*<pose>(\S+) (\S+)', world)]
    if len(carriers) != 3:
        raise SystemExit('carrier poses not found in the free world')
    mat = [math.dist(FAR_XY, c) for c in carriers]
    arm = [_segments(FAR_XY, tip, c, [ATTACH_RADIUS * v / math.hypot(*c) for v in c]) for c in carriers]
    ball = _to_segment(ball_xy, FAR_XY, tip)
    if min(mat) < FAR_CLEAR or min(arm) < FAR_CLEAR or ball < maw.BALL_CLEAR_NEWCOMER:
        raise SystemExit(f'far mat {FAR_XY}: {min(mat):.2f} m from a carrier, its arm {min(arm):.2f} m from a carrier '
                         f'cable, {ball:.2f} m from the ball')
    near, far = f'({x:g}, {y:g})', f'({FAR_XY[0]:g}, {FAR_XY[1]:g})'
    deg = math.degrees(yaw)
    name = name.replace('sq_', 'sq_far_', 1)
    far_model = free_model.replace('_pickup', '_far_pickup')
    text = _once(world, NEW_HEADER, NEW_HEADER.replace(' of 28 Oct)', ' of 28 Oct, QUAD4 on the far mat)'), name)
    text = _once(text, f'free on the floor at {near})', f'free on the floor at {far} behind the T, its arm laid out away '
                 'from the ring: the avoidance demo)', name)
    text = _once(text, f'Free start: on the floor at {near}, the arm laid out along +y with the magnet\n         on the '
                 'floor;', f'Far start (card 2026-10-28_attach_ambitious, the avoidance demo): on the floor at {far} '
                 f'behind the T, {min(mat):.2f} m\n         from the nearest carrier\'s spot, the arm laid out away from '
                 f'the ring (its pose turned {deg:.0f} deg, the body at yaw 0)\n         with the magnet on the floor at '
                 f'({tip[0]:.3f}, {tip[1]:.3f}), {min(arm):.2f} m from the nearest carrier\'s cable;\n        ', name)
    text = _once(text, f'<uri>models/{os.path.basename(free_model)}</uri>',
                 f'<uri>models/{os.path.basename(far_model)}</uri>', name)
    text = _once(text, f'<pose>{maw._f(x)} {maw._f(y)} {maw._f(z)} 0 0 0</pose>',
                 f'<pose>{maw._f(FAR_XY[0])} {maw._f(FAR_XY[1])} {maw._f(z)} 0 0 0</pose>', name)
    text, k = re.subn(r"\S+ m beside QUAD4's laid-out arm", f"{ball:.2f} m beside QUAD4's laid-out arm", text)
    if k != 1:
        raise SystemExit(f'{name}: the ball note not found exactly once')
    pose = f'<pose relative_to="base_link">0 0 {-maw.PIVOT_DZ:.4f} {roll:.6f} 0 '
    m = _once(model, pose + '0</pose>', pose + f'{yaw:.6f}</pose>', far_model)
    m = _once(m, 'GENERATED by tools/make_attach_worlds.py:', 'GENERATED by tools/make_attach_layout_worlds_p115.py '
              "(make_attach_worlds.py's free pickup newcomer, the arm turned):", far_model)
    m = _once(m, 'laid out along body +y with the magnet on the floor.', f'laid out along body ({ux:.3f}, {uy:.3f}) '
              f'with the magnet on the floor: the arm\'s pose turned\n         {deg:.0f} deg about the pivot, the '
              'body at yaw 0 (his reference yaw).', far_model)
    m = _once(m, f'for {maw.PICKUP_WORLDS["free"]}. -->', f'for {name}. -->', far_model)
    return {name: text, far_model: m}


def generate(spawns=SPAWNS):
    """{path under simulation_assets: text}. near: the two worlds and the welded newcomer; far: the free world with
    QUAD4 on the far mat and its newcomer."""
    with p115_ring(), tempfile.TemporaryDirectory() as tmp:
        texts = {rel: open(os.path.join(tmp, rel)).read() for rel in maw.generate(tmp)}
        free_model = os.path.join('models', maw.PICKUP_MODELS['free'])
        welded_model = os.path.join('models', maw.PICKUP_MODELS['welded'])
        xyz, roll = maw.spawn('free')
        spawn = (xyz, roll, maw.CABLE_LEN * math.sin(roll), maw.BALL_XY)
    for rel in (free_model, os.path.join('models', maw.BALL_COPY)):
        with open(os.path.join(maw.ASSETS, rel)) as f:
            if f.read() != texts[rel]:
                raise SystemExit(f'{rel} differs from the 1 m family: regenerate that first')
    out = {welded_model: _once(texts[welded_model], 'GENERATED by tools/make_attach_worlds.py',
                               'GENERATED by tools/make_attach_layout_worlds_p115.py (make_attach_worlds.py on the '
                               '1.15 kg payload of 28 Oct)', welded_model)}
    for rel in layout.KEEP:
        text = texts[rel].replace('(rig plates 3/11/7)', f'(rig plates {PLATES})')
        text = _once(_once(text, HEADER, NEW_HEADER, rel), RIM_NOTE, NEW_RIM_NOTE, rel)
        out[rel.replace('three_', 'sq_').replace('.sdf', f'{L100.SUFFIX}{SUFFIX}.sdf')] = text
    free_world = maw.PICKUP_WORLDS['free'].replace('three_', 'sq_').replace('.sdf', f'{L100.SUFFIX}{SUFFIX}.sdf')
    far = (far_spawn(free_world, out[free_world], free_model, texts[free_model], spawn) if 'far' in spawns else {})
    return {**(out if 'near' in spawns else {}), **far}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='fail if a file on disk differs from a fresh generation')
    ap.add_argument('--spawn', choices=SPAWNS, help="QUAD4's free start: near (0, 1.4) or the far mat (default both)")
    a = ap.parse_args()
    stale = []
    for name, text in generate((a.spawn,) if a.spawn else SPAWNS).items():
        path = os.path.join(maw.ASSETS, name)
        if a.check:
            if not os.path.exists(path) or open(path).read() != text:
                stale.append(name)
        else:
            with open(path, 'w') as f:
                f.write(text)
            print(f'wrote simulation_assets/{name}')
    if stale:
        print('stale: ' + ', '.join(stale))
        return 1
    if a.check:
        print('1.15 kg square attach worlds up to date')
    return 0


if __name__ == '__main__':
    sys.exit(main())
