def test_worlds_are_the_existing_1m_siblings_with_the_source_layout():
    from check_geometry import world_geometry
    for src, new in _pairs():
        assert new['world'] == src['world'].replace('.sdf', '_L100.sdf')
        g0 = world_geometry(os.path.join(ASSETS, src['world']))
        g1 = world_geometry(os.path.join(ASSETS, new['world']))
        assert g0['cable_len'] == pytest.approx(0.55) and g1['cable_len'] == pytest.approx(1.0)
        for k in ('attach_azimuths', 'num_drones', 'load_mass', 'attach_radius', 'attach_z', 'drone_mass'):
            assert g1[k] == pytest.approx(g0[k]), (new['name'], k)


def test_a_source_without_its_1m_world_is_skipped_never_flown_on_a_stand_in():
    want, skipped = G.build()
    made = {f[len(RS.PREFIX):-len('.yaml')] for f in want}
    assert made | set(skipped) == set(RS.sources()) and not made & set(skipped)
    for name in skipped:
        assert RS.missing_world(name), name
    for name in made:
        assert not RS.missing_world(name), name


def test_every_config_passes_the_runner_checks():
    import run_experiment as R
    from check_geometry import config_mismatches
    lp = os.path.join(G.REPO, 'src', 'bringup', 'launch', 'sim_control_launch.py')
    for src, new in _pairs():
        R.checked_config(os.path.join(G.OUT, new['name'] + '.yaml'))
        if src.get('mis_seed'):     # a robustness arm keeps the same deliberate errors, of the same size
            mis = lambda x: config_mismatches(os.path.join(ASSETS, x['world']), lp, x['launch']['args'])  # noqa: E731
            d0, d1 = ({k: c - w for k, w, c in mis(x)} for x in (src, new))
            assert d0.keys() == d1.keys() and all(d1[k] == pytest.approx(d0[k], abs=1e-6) for k in d0), new['name']


def test_batch_order():
    lab = G.order('lab')
    reps = RS.sources()
    want, _ = G.build()
    for f in want:
        assert lab.count(f'configs/experiments/{f}') == reps[f[len(RS.PREFIX):-len('.yaml')]]
    assert lab[:3] == ['configs/experiments/r1m_w4_da_release_hover.yaml'] * 3     # the 1 m ledger band first
    idx = lambda s: [i for i, p in enumerate(lab) if p.endswith(f'{s}.yaml')]  # noqa: E731
    assert max(idx('r1m_ta_a1_r1')) < min(idx('r1m_ta_a1_r2')) < min(idx('r1m_ta_a1_r3'))
    assert max(i for s in ('ta_a1_r1', 'dl_d4_gap240') for i in idx(f'r1m_{s}')) < min(idx('r1m_traj3_circle_v125'))
    carry = [i for i, p in enumerate(lab) if 'traj3_' in p]
    assert all(p.endswith('_v125.yaml') for p in [lab[i] for i in carry[:5]])
    assert max(carry) < min(i for i, p in enumerate(lab) if 'r1m_app_' in p)
    for p in lab + G.order('smoke'):
        assert os.path.isfile(os.path.join(G.REPO, p))
