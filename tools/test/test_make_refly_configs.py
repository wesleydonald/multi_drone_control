ASSETS = os.path.join(G.REPO, 'simulation_assets')
CHANGED = {'world', 'launch.args.cable_len', 'launch.args.traj_hold_s', 'timing.duration_s',
           'io_launch.args.tether_len', 'launch.args.attach_cable_len'}


def _flat(cfg):
    out = {}

    def walk(p, v):
        if isinstance(v, dict):
            for k, x in v.items():
                walk(f'{p}.{k}' if p else k, x)
        else:
            out[p] = v
    walk('', {k: v for k, v in cfg.items() if k not in ('name', 'description', 'events', 'lab_env', 'record')})
    return out


def _pairs():
    want, _ = G.build()
    for f in sorted(want):
        src = f[len(RS.PREFIX):-len('.yaml')]
        with open(os.path.join(G.OUT, f)) as fh:
            yield G.load(src), yaml.safe_load(fh)


def test_check_passes_and_every_file_reads_back_as_generated():
    assert G.main(['--check']) == 0
    want, _ = G.build()
    for f, text in want.items():
        assert text.startswith('# GENERATED by tools/make_refly_configs.py')
        with open(os.path.join(G.OUT, f)) as fh:
            assert fh.read() == text


def test_only_what_the_cable_needs_differs_from_the_source():
    for src, new in _pairs():
        fs, fn = _flat(src), _flat(new)
        diff = {k for k in set(fs) | set(fn) if fs.get(k) != fn.get(k)}
        assert diff <= CHANGED, (new['name'], diff - CHANGED)
        assert new['name'] == RS.PREFIX + src['name'] and RS.CARD in new['description']
        assert [(e['do'], e.get('arg')) for e in new['events']] == [(e['do'], e.get('arg')) for e in src['events']]
        assert new['record'] == G.RECORD


def test_the_cable_rule_keeps_a_typed_rod_error_absolute():
    for src, new in _pairs():
        a, b = src['launch']['args'], new['launch']['args']
        assert b['cable_len'] == pytest.approx(a['cable_len'] + 0.45)
        assert new.get('mis_seed') == src.get('mis_seed')
        assert 'attach_cable_len' not in b
    rod = yaml.safe_load(open(os.path.join(G.OUT, 'r1m_app_rob_rod+5_int.yaml')))
    assert rod['launch']['args']['cable_len'] == pytest.approx(1.05) and rod['mis_seed'] is True


def test_event_shifts_hold_and_duration():
    for src, new in _pairs():
        a = src['launch']['args']
        path = str(a.get('load_traj', 'hover')) != 'hover'
        shift = G.HOLD_S if path and G.held(a) is None else 0.0
        if path:
            assert G.held(new['launch']['args']) is not None
        if shift:
            assert new['launch']['args']['traj_hold_s'] == G.HOLD_S
        after = False
        for e0, e1 in zip(src['events'], new['events']):
            assert e1['t'] == pytest.approx(e0['t'] + (shift if after else 0.0)), (new['name'], e0)
            after = after or e0['do'] == 'WAIT_LIFT'
        assert new['timing']['duration_s'] == pytest.approx(src['timing']['duration_s'] + shift + G.DURATION_EXTRA_S)
    # the paths that already hold (T15, W5) and every hover keep their timing
    for name in ('ta_a7_circle60', 'w4_gi_g2_release_orbit', 'ta_a1_r1', 'dl_d1_second_loss'):
        new = yaml.safe_load(open(os.path.join(G.OUT, f'r1m_{name}.yaml')))
        assert [e['t'] for e in new['events']] == [e['t'] for e in G.load(name)['events']]


def test_the_figure8_keeps_its_flown_size_and_the_size_switch_moves_land(monkeypatch):
    for src, new in _pairs():
        if src['launch']['args'].get('load_traj') == 'fig_8':
            assert new['launch']['args']['fig8_size'] == src['launch']['args']['fig8_size'] == 0.5
    monkeypatch.setattr(G, 'FIG8_SIZE', 1.0)
    src = G.load('traj3_fig8_v125')
    new, notes = G.transform(src)
    extra = math.ceil(G.fig8_lap_s(1.0, 0.125) - G.fig8_lap_s(0.5, 0.125))
    assert extra == 25 and new['launch']['args']['fig8_size'] == 1.0
    land = lambda c: [e['t'] for e in c['events'] if e['do'] == 'LAND'][0]  # noqa: E731
    assert land(new) == pytest.approx(land(src) + G.HOLD_S + extra)


