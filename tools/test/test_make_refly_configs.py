"""tools/make_refly_configs.py (thesis R, card docs/experiments/2026-10-23_refly_1m.md): the r1m_ configs on disk are
the generated ones, each differs from its 0.55 m source only in what the cable length needs, and every one passes
run_experiment.py's checks on a world that reads back 1 m with its source world's layout."""
import math
